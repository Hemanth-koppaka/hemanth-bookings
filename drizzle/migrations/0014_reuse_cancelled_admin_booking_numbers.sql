CREATE OR REPLACE FUNCTION public.assign_admin_booking_number()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE candidate bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('hb-admin-booking-number'));
  IF NEW.status = 'cancelled' OR coalesce(NEW.meta->>'status', '') IN ('cancelled', 'no-show') THEN
    NEW.booking_no := NULL;
    RETURN NEW;
  END IF;
  IF TG_OP = 'INSERT' OR NEW.booking_no IS NULL THEN
    SELECT min(n) INTO candidate FROM (
      SELECT 1::bigint AS n
      UNION ALL
      SELECT b.booking_no + 1 FROM public.bookings b WHERE b.booking_no > 0
    ) candidates
    WHERE NOT EXISTS (SELECT 1 FROM public.bookings b WHERE b.booking_no = candidates.n);
    NEW.booking_no := candidate;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.assign_admin_booking_number() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.assign_admin_booking_number() TO service_role;
CREATE TRIGGER bookings_assign_admin_number BEFORE INSERT OR UPDATE ON public.bookings FOR EACH ROW EXECUTE FUNCTION public.assign_admin_booking_number();
CREATE OR REPLACE FUNCTION public.next_booking_reference()
RETURNS TABLE(reference text, booking_no bigint)
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  reference := NULL;
  booking_no := NULL;
  RETURN NEXT;
END;
$$;
REVOKE ALL ON FUNCTION public.next_booking_reference() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.next_booking_reference() TO service_role;
COMMENT ON FUNCTION public.next_booking_reference() IS 'Compatibility RPC: random guest references are generated by the application; admin numbers are allocated atomically at insert.';